/**
 * Normalizes a slug or string for matching
 */
const normalizeKey = (str) => {
  if (!str) return '';
  return str.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');
};

/**
 * Returns a scheme object localized according to the current language.
 * When lang === 'ta', translates name, descriptions, category, department,
 * benefits, documents, process, dates, and government level.
 */
export const getLocalizedScheme = (scheme, lang = 'en') => {
  if (!scheme) return scheme;
  if (lang !== 'ta') {
    return scheme;
  }

  // Find translation by slug or name
  const slugKey = normalizeKey(scheme.slug);
  const nameKey = normalizeKey(scheme.name);

  const tData = SCHEMES_TAMIL[slugKey] || SCHEMES_TAMIL[nameKey] || Object.values(SCHEMES_TAMIL).find(
    (s) => normalizeKey(s.name) === nameKey
  );

  const categoryName = CATEGORY_TRANSLATIONS[scheme.category?.slug] ||
    CATEGORY_TRANSLATIONS[scheme.category_name] ||
    CATEGORY_TRANSLATIONS[scheme.category?.name] ||
    scheme.category_name ||
    scheme.category?.name;

  const departmentName = DEPARTMENT_TRANSLATIONS[scheme.department?.name] ||
    DEPARTMENT_TRANSLATIONS[scheme.department_name] ||
    scheme.department_name ||
    scheme.department?.name;

  const isCentral = scheme.government_level === 'Central';
  const governmentLevelTa = isCentral ? 'மத்திய அரசுத் திட்டம்' : 'மாநில அரசுத் திட்டம்';
  const stateTa = scheme.state === 'Tamil Nadu' ? 'தமிழ்நாடு' : (scheme.state === 'All India' ? 'அகில இந்தியா' : scheme.state);

  if (!tData) {
    // Partial translation if not explicitly in table
    return {
      ...scheme,
      government_level_display: governmentLevelTa,
      state_display: stateTa,
      category_name: categoryName || scheme.category_name,
      department_name: departmentName || scheme.department_name,
    };
  }

  // Combine full translation
  return {
    ...scheme,
    name: tData.name || scheme.name,
    short_description: tData.short_description || scheme.short_description,
    full_description: tData.full_description || scheme.full_description,
    benefits_summary: tData.benefits_summary || scheme.benefits_summary,
    department_name: tData.department_name || departmentName || scheme.department_name,
    department: scheme.department ? {
      ...scheme.department,
      name: tData.department_name || departmentName || scheme.department.name
    } : null,
    category_name: tData.category_name || categoryName || scheme.category_name,
    category: scheme.category ? {
      ...scheme.category,
      name: tData.category_name || categoryName || scheme.category.name
    } : null,
    application_deadline: tData.application_deadline || scheme.application_deadline,
    application_status: tData.application_status || scheme.application_status,
    application_process: tData.application_process || scheme.application_process,
    government_level_display: governmentLevelTa,
    state_display: stateTa,
    benefits: (tData.benefits && tData.benefits.length > 0)
      ? tData.benefits.map((b, idx) => ({
          ...b,
          id: (scheme.benefits && scheme.benefits[idx]?.id) || idx + 1,
        }))
      : scheme.benefits,
    documents: (tData.documents && tData.documents.length > 0)
      ? tData.documents.map((dName, idx) => ({
          id: (scheme.documents && scheme.documents[idx]?.id) || idx + 1,
          document_name: dName,
          is_mandatory: true
        }))
      : scheme.documents,
  };
};
